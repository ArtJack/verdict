#!/usr/bin/env python3
"""Hygiene — the junk a product accumulates, and the few exposures a pattern can
prove, measured on every run. Stdlib only, like the rest of the harness.

More and more of what Verdict reviews was generated by a model and shipped by
someone who never read it. Three tiers, and the tier decides who acts:

  1  near-certain and harmful — a live key in the source, a committed secrets
     file, a client-side variable named as a secret, database rules open to
     everyone, a debugger left in: filed as findings by verdict-finalize,
     `source: "hygiene"`
  2  junk — swallowed errors, unused imports, oversized files, TODOs,
     commented-out code, debug logging, copied functions: tracked in a ledger,
     never a finding
  3  leads — a swallow around a secret write, a security read that fails open, a
     placeholder secret default, a forwarded header, a wildcard CORS rule: handed
     to the tester to read first, never filed here

Tier 1 is filed with no model in the loop, so it takes only what is certain. An
encrypted file, a key that is public by design, a value that is not a credential,
a rule that only lets anyone read one collection, a debugger in a comment: each
is a lead or nothing, never a finding.

The scan reads what HEAD holds, through git, and never the working copy:
"committed" means committed. A file that exists only on disk, a symlink pointing
out of the repository, a FIFO — none of them is ever opened. Outside a git
checkout, or before the first commit, the scan reports itself unavailable rather
than walking the directory and calling what it finds there committed.

A file git cannot hand over (a partial clone's missing blob, a stream that broke)
or whose checks raise is named in `scope.failed_paths`, and the scan says
`partial`: what it found is real, and its silence about those files is no proof
they are clean. When no file could be read at all, it says unavailable. A SQL
migration too large to read is named apart, in `scope.rls_unread`: it decides which
tables are open, so none is filed while it is unread, but it is no failure — a
committed dump would otherwise leave every run partial.

Every item carries a fingerprint (kind, path, normalized line, occurrence), so a
line that moves keeps its identity; a client-side variable is known by its name,
wherever it is read. An item the scan stops seeing resolves only on evidence —
every file it lives in was read without it, or has left the tree (Evidence) —
never on the silence of a file nobody read.

A secret is redacted where it is found, and every other excerpt and reason is
scrubbed on its way out: provider-format keys, JWTs, the password in a URL and
runs that look random are removed. A digit-free, word-like token cannot be told
from prose, so no scrub can promise to catch one. Lines are numbered by splitting on "\\n",
never `splitlines()`, which also breaks on U+2028 inside a string literal and
shifts every later line number — once CRLF and a lone CR are made "\\n", as
Python's own parser does.
"""


"""The language table: which files `verdict-local` reads, in which language, and which it leaves.

A website is TypeScript and HTML, or PHP, or Ruby, or Go behind a React front end. A file this table
does not name is a file no question is ever asked about, so each ecosystem's own conventions are
pinned here: where its tests live, what its generators write, and which folders hold code nobody in
the project wrote.
"""

import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))
from verdict_mcp import languages  # noqa: E402


@pytest.mark.parametrize("path, lang", [
    ("app/api/route.ts", "typescript"), ("src/App.tsx", "typescript"), ("web/app.jsx", "javascript"),
    ("cmd/server/main.go", "go"), ("src/lib.rs", "rust"), ("src/main/java/shop/Orders.java", "java"),
    ("app/src/main/kotlin/Cart.kt", "kotlin"), ("Sources/App/View.swift", "swift"),
    ("lib/widget.dart", "dart"), ("src/math.c", "c"), ("include/shop.hpp", "cpp"),
    ("app/Http/Controllers/OrderController.php", "php"), ("contracts/Token.sol", "solidity"),
    ("resources/views/orders/show.blade.php", "blade"), ("app/controllers/orders_controller.rb", "ruby"),
    ("Rakefile", "ruby"), ("lib/shop_web/router.ex", "elixir"), ("init.lua", "lua"),
    ("src/Counter.vue", "vue"), ("src/routes/+page.svelte", "svelte"), ("src/pages/index.astro", "astro"),
    ("public/index.html", "html"), ("Pages/Index.cshtml", "razor"), ("templates/base.html.j2", "jinja"),
    ("app/views/orders/show.html.erb", "erb"), ("deploy.sh", "shell"), ("db/schema.sql", "sql"),
    ("scripts/setup.ps1", "powershell"), ("scripts/seed.py", "python"),
])
def test_every_language_a_website_is_built_in_has_a_reader(path, lang):
    assert languages.language_of(path) == lang
    assert languages.family_of(lang) in languages.FAMILIES


@pytest.mark.parametrize("path", ["README.md", "package.json", "styles/site.css", "app/globals.scss",
                                  "docker-compose.yml", "public/logo.svg", ".env", "Makefile",
                                  "tsconfig.json", "prisma/schema.prisma", "yarn.lock"])
def test_what_is_not_program_source_is_not_read(path):
    assert languages.language_of(path) is None
    assert not languages.readable(path)


@pytest.mark.parametrize("path", [
    "web/src/App.test.tsx", "web/src/app.spec.ts", "web/e2e/login.ts", "cypress/e2e/checkout.cy.ts",
    "src/components/Button.stories.tsx", "pkg/orders/orders_test.go",
    "src/test/java/shop/OrdersTest.java", "app/src/test/kotlin/CartTest.kt",
    "spec/models/order_spec.rb", "test/shop_web/user_controller_test.exs",
    "tests/Feature/OrderTest.php", "Tests/AppTests/CartTests.swift", "test/widget_test.dart",
    "src/Api.Tests/OrdersTests.cs", "tests/integration.rs", "spec/cart_spec.lua", "web/__tests__/x.js",
])
def test_tests_are_known_by_every_ecosystems_own_conventions(path):
    assert languages.is_test_path(path), path
    assert not languages.readable(path), path


@pytest.mark.parametrize("path", ["src/Latest.cs", "src/contest.ts", "lib/latest.go",
                                  "src/testing-utils-free.ts", "app/AbstractTestable.java",
                                  "app/models/contest_entry.rb"])
def test_a_name_that_only_contains_test_is_code(path):
    assert not languages.is_test_path(path), path
    assert languages.readable(path), path


@pytest.mark.parametrize("path", [
    "api/v1/orders.pb.go", "internal/store/mock_store.go", "pkg/apis/zz_generated.deepcopy.go",
    "lib/models/order.freezed.dart", "lib/models/order.g.dart", "web/dist/app.js",
    "target/classes/A.java", "build/generated/X.kt", "deps/plug/lib/plug.ex", "_build/dev/lib/x.ex",
    "vendor/laravel/framework/src/X.php", "wp-includes/load.php", "public/lib/jquery.js",
    "Pods/Alamofire/Source/AF.swift", ".svelte-kit/generated/root.svelte", "web/src/types.d.ts",
])
def test_generated_vendored_and_built_code_is_not_read(path):
    assert languages.is_generated(path), path
    assert not languages.readable(path), path


def test_a_source_folder_named_like_build_output_is_still_read():
    assert languages.readable("src/build/plan.ts"), "inside a source tree, `build` is a module"
    assert not languages.readable("build/plan.ts"), "beside it, `build` is output"


def test_a_generated_file_or_a_bundle_is_known_by_its_content():
    assert languages.looks_generated("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n")
    assert languages.looks_generated("// <auto-generated />\nnamespace X;\n")
    assert languages.looks_generated("!function(){" + "var a=1;" * 600 + "}()")
    assert languages.looks_generated("\x00\x01\x02 an MPEG stream named .ts")
    assert not languages.looks_generated("export function f() {\n  return 1\n}\n" * 200)


def test_what_a_range_changed_that_no_reader_reads_is_counted_by_kind():
    changed = ["a.css", "b.scss", "package.json", "README.md", "app/page.ts", "logo.png", ".env.local"]
    assert languages.unread_summary(changed) == ("2 stylesheet(s), 2 configuration or data file(s), "
                                                 "1 document(s), 1 image or font(s)")
    assert languages.unread_summary(["app/page.ts"]) == ""


def test_templates_are_named_as_templates():
    assert languages.is_template("blade") and languages.is_template("jinja")
    assert not languages.is_template("php") and not languages.is_template("vue")
